export function buildUniqueSupermarketProducts(): SupermarketProduct[] {
  const now = Date.now();
  return UNIQUE_SEEDS.map((seed, index) => {
    const discountPercent = Math.round(
      ((seed.originalPrice - seed.price) / seed.originalPrice) * 100
    );
    return {
      id: seed.id,
      sku: seed.sku,
      name: seed.name,
      slug: seed.slug,
      category: seed.category,
      subcategory: seed.subcategory,
      brand: seed.brand,
      weight: seed.weight,
      price: seed.price,
      originalPrice: seed.originalPrice,
      discountPercent,
      offerLabel: seed.offerLabel,
      description: seed.description,
      specifications: {
        Brand: seed.brand,
        Department: seed.category,
        Subcategory: seed.subcategory,
        'Pack Size': seed.weight,
        Origin: seed.origin,
        'Shelf Life': seed.shelfLife,
        'GST Rate': `${seed.gstPercent}%`,
        SKU: seed.sku,
      },
      image: seed.image,
      stock: 18 + ((index * 7) % 45),
      popularity: seed.popularity,
      rating: seed.rating,
      reviewCount: 28 + index * 4,
      reviews: [
        {
          id: `rev-${seed.id}-1`,
          userName: seed.reviewerName,
          rating: 5,
          title: seed.reviewTitle,
          comment: seed.reviewComment,
          verifiedPurchase: true,
          createdAt: new Date(now - (index + 1) * 86400000).toISOString(),
        },
      ],
      isTodayDeal: Boolean(seed.isTodayDeal),
      isBestSeller: Boolean(seed.isBestSeller),
      isTrending: Boolean(seed.isTrending),
      isNewArrival: Boolean(seed.isNewArrival),
      isDailyEssential: Boolean(seed.isDailyEssential),
      isRecommended: Boolean(seed.isRecommended),
      gstPercent: seed.gstPercent,
      createdAt: new Date(now - index * 3600000).toISOString(),
    };
  });
}

